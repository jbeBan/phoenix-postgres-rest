defmodule SurveyApi.SchemaTest do
  @moduledoc """
  The CHECK constraints are the second line of defence behind SurveyApi.Validation; prove they bite on their
  own, and that the migration created the objects the code relies on.
  """

  use ExUnit.Case, async: true

  alias Ecto.Adapters.SQL.Sandbox
  alias SurveyApi.Repo

  setup do
    pid = Sandbox.start_owner!(Repo, shared: false)
    on_exit(fn -> Sandbox.stop_owner(pid) end)

    %{rows: [[survey_id]]} =
      Repo.query!("INSERT INTO surveys (title) VALUES ('placeholder') RETURNING id")

    {:ok, survey_id: survey_id}
  end

  @insert "INSERT INTO responses (survey_id, respondent, rating, comment) VALUES ($1, $2, $3, $4)"

  defp constraint_violated(sql, params) do
    {:error, %Postgrex.Error{postgres: %{code: :check_violation, constraint: constraint}}} =
      Repo.query(sql, params)

    constraint
  end

  test "surveys.title must be 1..200 characters" do
    for title <- ["", String.duplicate("x", 201)] do
      assert constraint_violated("INSERT INTO surveys (title) VALUES ($1)", [title]) ==
               "surveys_title_check"
    end
  end

  test "responses reject values the API would never send", %{survey_id: sid} do
    long = fn n -> String.duplicate("x", n) end

    assert constraint_violated(@insert, [sid, "", 3, nil]) == "responses_respondent_check"
    assert constraint_violated(@insert, [sid, long.(201), 3, nil]) == "responses_respondent_check"
    assert constraint_violated(@insert, [sid, "a", 0, nil]) == "responses_rating_check"
    assert constraint_violated(@insert, [sid, "a", 6, nil]) == "responses_rating_check"
    assert constraint_violated(@insert, [sid, "a", 3, long.(2001)]) == "responses_comment_check"
  end

  test "the database accepts the boundary values", %{survey_id: sid} do
    Repo.query!("INSERT INTO surveys (title) VALUES ($1)", [String.duplicate("x", 200)])

    for rating <- [1, 5] do
      assert {:ok, _} =
               Repo.query(@insert, [
                 sid,
                 String.duplicate("x", 200),
                 rating,
                 String.duplicate("x", 2000)
               ])
    end
  end

  test "the foreign key and the composite index exist" do
    %{rows: [[index]]} =
      Repo.query!(
        "SELECT indexdef FROM pg_indexes WHERE indexname = 'idx_responses_survey_id_id'"
      )

    assert index =~ "(survey_id, id)"

    %{rows: [[fk]]} =
      Repo.query!(
        "SELECT conname FROM pg_constraint WHERE conname = 'responses_survey_id_fkey' AND contype = 'f'"
      )

    assert fk == "responses_survey_id_fkey"
  end

  test "ids and timestamps are generated by the database", %{survey_id: sid} do
    %{rows: [[id, created_at]]} =
      Repo.query!(@insert <> " RETURNING id, created_at", [sid, "a", 3, nil])

    assert is_integer(id)
    assert %DateTime{} = created_at
  end
end
